const fs = require("fs");
const path = require("path");
const { AREAS, SPEC_AREAS, suiteForPath, defaultAreaForPath, validBlocks } = require("./areas");
const { parseHelpers, parseCommands, parseSelectors, sourceHash } = require("./parse");

const OUT_DIR = "cypress/support/suiteIndex";
const SKIP_DIRS = ["cypress/support/suiteIndex", "cypress/support/componentAutomation"];
const COMMON_KEYS = ["cancelButton", "saveButton", "modalTitle", "modalMessage", "toastMessage", "nameInput", "modalCloseButton"];

function listJs(rootDir, rel) {
  const abs = path.join(rootDir, rel);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs, { withFileTypes: true }).flatMap(e => {
    const child = path.posix.join(rel, e.name);
    if (e.isDirectory()) return SKIP_DIRS.includes(child) ? [] : listJs(rootDir, child);
    return e.name.endsWith(".js") ? [child] : [];
  }).sort();
}

function areasFor(rec) {
  const suite = suiteForPath(rec.file);
  if (suite === "appBuilder") return ["appBuilder"];
  if (rec.block && AREAS.includes(rec.block) && validBlocks(suite).includes(rec.block)) return [rec.block];
  return [defaultAreaForPath(rec.file)];
}

function codeRecord(r, overrides = []) {
  return {
    id: `${r.kind}:${r.name}`, kind: r.kind, name: r.name, file: r.file, line: r.line,
    areas: areasFor(r), type: r.type, usage: r.usage, dom: r.dom, signature: r.signature,
    hash: r.hash, overrides,
  };
}

function selectorRecord(r) {
  return {
    id: `selector:${r.name}`, kind: "selector", name: r.name, file: r.file, line: r.line,
    areas: areasFor(r), hash: sourceHash(r.expression), dynamic: r.dynamic, params: r.params,
    expression: r.expression, common: false,
  };
}

function collectSymbols(rootDir) {
  const warnings = [];
  const read = (f) => fs.readFileSync(path.join(rootDir, f), "utf8");
  const helpers = [];
  for (const f of listJs(rootDir, "cypress/support")) {
    const r = parseHelpers(read(f), f);
    helpers.push(...r.records); warnings.push(...r.warnings);
  }
  const commands = [];
  for (const f of listJs(rootDir, "cypress/commands")) {
    const r = parseCommands(read(f), f);
    commands.push(...r.records); warnings.push(...r.warnings);
  }
  const selectors = [];
  for (const f of listJs(rootDir, "cypress/constants/selectors")) {
    const r = parseSelectors(read(f), f);
    selectors.push(...r.records); warnings.push(...r.warnings);
  }

  const records = helpers.map(h => codeRecord(h));
  const byName = new Map();
  for (const c of commands) {
    if (!byName.has(c.name)) byName.set(c.name, { adds: [], overwrites: [] });
    byName.get(c.name)[c.overwrite ? "overwrites" : "adds"].push(c);
  }
  for (const { adds, overwrites } of byName.values()) {
    const overrides = overwrites.map(o => `${o.file}:${o.line}`);
    if (adds.length) adds.forEach(a => records.push(codeRecord(a, overrides)));
    else overwrites.forEach(o => records.push(codeRecord(o)));
  }
  const lastKeyFiles = new Map();
  for (const s of selectors) {
    const last = s.name.split(".").pop();
    if (!lastKeyFiles.has(last)) lastKeyFiles.set(last, new Set());
    lastKeyFiles.get(last).add(s.file);
  }
  for (const s of selectors) {
    const rec = selectorRecord(s);
    const last = s.name.split(".").pop();
    rec.common = COMMON_KEYS.includes(last) || lastKeyFiles.get(last).size >= 3;
    records.push(rec);
  }

  const groups = new Map();
  for (const r of records) {
    if (!groups.has(r.id)) groups.set(r.id, []);
    groups.get(r.id).push(r);
  }
  const collisions = [];
  for (const [id, list] of groups) {
    const files = [...new Set(list.map(r => r.file))];
    if (files.length < 2) continue;
    collisions.push({ id, files: files.sort() });
    for (const r of list) r.id = `${id}@${r.file}`;
  }
  // a same-file duplicate keeps a unique id by line
  const seen = new Set();
  for (const r of records) {
    if (seen.has(r.id)) r.id = `${r.id}#${r.line}`;
    seen.add(r.id);
  }

  const symbols = records.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  collisions.sort((a, b) => (a.id < b.id ? -1 : 1));
  return { symbols, collisions, warnings };
}

const cell = (v) => String(v == null ? "" : v).replace(/\|/g, "\\|").replace(/[\r\n]+/g, " ").trim();
const clip = (v, n = 120) => (v.length > n ? v.slice(0, n - 1) + "…" : v);

function areaIndex(area, symbols) {
  const rows = symbols.filter(s => s.areas.includes(area));
  const lines = [
    `# ${area} symbols (AUTO-GENERATED by tools/suite-index/generate.js — do not edit; run npm run suite:index)`,
    "",
    `${rows.length} symbols. Look up with: npm run suite:find -- ${area} <words>`,
    "",
    "| name | kind | file:line | usage |",
    "|---|---|---|---|",
  ];
  for (const s of rows) {
    const usage = s.kind === "selector" ? clip(s.expression) : s.usage;
    lines.push(`| ${cell(s.name)} | ${s.kind} | ${cell(`${s.file}:${s.line}`)} | ${usage ? "`" + cell(usage) + "`" : ""} |`);
  }
  return lines.join("\n") + "\n";
}

function router(symbols) {
  const lines = [
    "# suite index router (AUTO-GENERATED by tools/suite-index/generate.js — do not edit; run npm run suite:index)",
    "",
    "| area | spec folders | config | symbols | tagged |",
    "|---|---|---|---|---|",
  ];
  for (const area of AREAS) {
    const entries = SPEC_AREAS.filter(e => e.area === area);
    const globs = entries.flatMap(e => e.specGlobs).map(g => "`" + g + "`").join("<br>");
    const configs = [...new Set(entries.map(e => e.config))].map(c => "`" + c + "`").join("<br>");
    const own = symbols.filter(s => s.areas.includes(area));
    const tagged = own.filter(s => s.kind !== "selector" && s.usage).length;
    lines.push(`| ${area} | ${globs || "-"} | ${configs || "-"} | ${own.length} | ${tagged} |`);
  }
  return lines.join("\n") + "\n";
}

function renderOutputs(symbols, collisions) {
  const out = new Map();
  out.set(`${OUT_DIR}/symbols.json`, JSON.stringify({ generatedBy: "tools/suite-index/generate.js", symbols, collisions }, null, 2) + "\n");
  out.set(`${OUT_DIR}/router.md`, router(symbols));
  for (const area of AREAS) out.set(`${OUT_DIR}/${area}/index.md`, areaIndex(area, symbols));
  return out;
}

function writeOutputs(rootDir) {
  const { symbols, collisions, warnings } = collectSymbols(rootDir);
  for (const [rel, text] of renderOutputs(symbols, collisions)) {
    fs.mkdirSync(path.dirname(path.join(rootDir, rel)), { recursive: true });
    fs.writeFileSync(path.join(rootDir, rel), text);
  }
  return { symbols, collisions, warnings };
}

// Views for humans and grep, written to the gitignored suiteIndex/ folder. suite:find does not need them.
if (require.main === module) {
  const { symbols, collisions, warnings } = writeOutputs(path.join(__dirname, "../.."));
  for (const w of warnings) console.error(`warning ${w.file}:${w.line} ${w.message}`);
  console.log(`suite:index: ${symbols.length} symbols, ${collisions.length} collisions, ${warnings.length} warnings -> ${OUT_DIR}/`);
}

module.exports = { collectSymbols, renderOutputs, writeOutputs, listJs, OUT_DIR };
