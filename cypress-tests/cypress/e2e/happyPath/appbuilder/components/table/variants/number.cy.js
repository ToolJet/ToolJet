  it("column manager — duplicating a `number` column keeps its name (F18)", () => {
    addColumnOfType(
      tableText.variantNewNumberColumn,
      tableText.columnTypeValue.number, // source: PropertiesTabElements.jsx:126
      tableText.variantNumberColumnKey // source: table.js:692
    );
    closeColumnPopover(tableText.variantNewNumberColumn);

    // PRODUCT BUG F18 (MED): duplicateWithNewId (shared/utils/listItemHelpers.js:45-48)
    // copies the item verbatim and swaps ONLY the uuid, so the clone keeps the same
    // display name. duplicateColumn already asserts the two colliding list rows; the
    // rendered side collides too, because TableHeader.jsx:153 derives the header
    // data-cy from that same name. Asserting the collision documents the bug instead
    // of hiding it behind a .first().
    duplicateColumn(tableText.variantNewNumberColumn);
    cy.forceClickOnCanvas();
    cy.get(tableSelector.columnHeader(tableText.variantNewNumberColumn)).should(
      "have.length",
      2
    ); // source: listItemHelpers.js:45-48
  });

  // ═══════════════════════════════════════════════════════════════════════════
  // TYPE-SPECIFIC PROPERTY — Decimal Places (PropertiesTabElements.jsx:367-384)
  // ═══════════════════════════════════════════════════════════════════════════

  it("properties — Decimal Places truncates the rendered value and exposes no fx button", () => {
    // The seed `phone` value is an INTEGER and removingExcessDecimalPlaces returns
    // any value without a '.' untouched (NumberRenderer.jsx:27-34), so decimalPlaces
    // has no observable effect on it. Seed a decimal dataset instead:
    // autogenerateColumns ships ON (table.js:712), so the new `amount` key generates
    // its own number column (autoGenerateColumns.js:85-100, :110-119).
    setTableData(tableText.variantNumberDecimalData);
    cy.forceClickOnCanvas();
    cy.get(
      tableSelector.cell(tableText.variantDecimalColumn, 0, W)
    ).scrollIntoView();
    verifyCellType(
      tableText.variantDecimalColumn,
      0,
      tableText.cellClassByType.number,
      W
    ); // source: TableRow.jsx:120
    // Untouched to start with — `decimalPlaces` has no default, so
    // NumberColumnAdapter.jsx:25 resolves it to null and :73 skips the truncation.
    verifyCellValue(
      tableText.variantDecimalColumn,
      0,
      tableText.variantDecimalRawRow0,
      W
    ); // source: NumberRenderer.jsx:73

    openColumnPopover(tableText.variantDecimalColumn);
    // decimalPlaces is a BARE CodeHinter (not ProgramaticallyHandleProperties), so
    // it never renders an FxButton at all — its only "fx" is that the field itself
    // is always a code editor.
    verifyColumnFxAbsent(tableText.labelDecimalPlaces); // source: PropertiesTabElements.jsx:369-382
    // NOT ASSERTED ON THE EDITOR: `decimalPlaces` has no default —
    // initialValue={column?.decimalPlaces} is undefined and `{{2}}` is only the
    // PLACEHOLDER (:371-374). Reading that back through `.cm-line` is unsafe,
    // because CodeMirror 6's placeholder extension renders `.cm-placeholder`
    // INSIDE the first `.cm-line`, so an empty editor's text is the placeholder
    // string rather than ''. The untruncated 3.14159 asserted above is the
    // unambiguous, behavioural proof that no default is applied
    // (NumberColumnAdapter.jsx:25 → null → NumberRenderer.jsx:73 skips).
    // F29: this field is the one Properties-tab control with no data-cy — see the
    // selector's own comment for why `.field.mb-2.px-3:not([data-cy])` isolates it
    // for a `number` column.
    setColumnCodeField(
      tableSelector.columnDecimalPlacesField,
      tableText.variantDecimalPlaces
    ); // source: PropertiesTabElements.jsx:367-384
    closeColumnPopover(tableText.variantDecimalColumn);

    cy.forceClickOnCanvas();
    cy.get(
      tableSelector.cell(tableText.variantDecimalColumn, 0, W)
    ).scrollIntoView();
    // removingExcessDecimalPlaces splits on '.' and slices the fraction to the
    // allowed length, so 3.14159 renders as 3.14.
    verifyCellValue(
      tableText.variantDecimalColumn,
      0,
      tableText.variantDecimalTruncatedRow0,
      W
    ); // source: NumberRenderer.jsx:27-34, :73
  });

  // ═══════════════════════════════════════════════════════════════════════════
