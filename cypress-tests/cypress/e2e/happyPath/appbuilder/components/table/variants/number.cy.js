/**
 * SPEC — Table — variants/number.
 *
 * FOR AI: covers the `number` COLUMN TYPE of the Table widget end to end — type
 * switching, column creation / duplication / deletion, its ONE type-specific
 * property (Decimal Places), the shared column controls, the two style controls
 * it exposes, all four validations it mounts and the rendered cell contract.
 * Source root: frontend/src/AppBuilder/RightSideBar/Inspector/Components/Table/
 * (`columns` is declared bare as `type:'array'` at table.js:44, so NONE of these
 * controls live in the widget config — they live in the ColumnManager).
 *
 * ── WHAT MAKES `number` DIFFERENT ───────────────────────────────────────────
 *   1. it is the ONLY type with `decimalPlaces` (PropertiesTabElements.jsx:367-384),
 *      and that field is unaddressable by data-cy — see F29 below;
 *   2. its <td> discriminator is `has-number` (TableRow.jsx:120) and it does NOT
 *      get `has-textarea`;
 *   3. an EDITABLE number cell renders a real `<input type="number">` plus a
 *      stepper (NumberRenderer.jsx:141-196) rather than text, so its value must
 *      be read with have.value, not have.text;
 *   4. it swaps string/text's Min length + Max length for Min value + Max value
 *      (ValidationProperties.jsx:74-96).
 *
 * ── WHY THE AUTO-GENERATED `phone` COLUMN IS THE SEED ───────────────────────
 * The shipped `columns` default declares a number column keyed `mobile_number`
 * (table.js:768) — but the shipped dataset has no such key; row 0 carries
 * `phone: 9876543210` (table.js:692). autoGenerateColumns.js:90-92 keeps an
 * `autogenerated` column only while its key is still present in the data, so
 * `mobile_number` is silently DROPPED; :85-100 then generates a fresh column for
 * the unmatched `phone` key whose columnType is
 * `convertDataTypeToColumnType(typeof 9876543210)` = 'number' (:110-119).
 * The result is a real, data-bound `number` column, already proven to exist at
 * runtime by inspector.cy.js:98 and properties.cy.js:166-170. Driving THAT column
 * means every assertion runs against real seed data; the first it-block asserts
 * the config-vs-data divergence explicitly instead of assuming it. Column
 * creation / duplication / deletion get their own it-blocks, where creation is
 * what is under test, and the Decimal Places block seeds its own decimal dataset
 * (the seed `phone` value is an integer, on which decimalPlaces is a no-op —
 * NumberRenderer.jsx:27-34 returns the value untouched when it has no '.').
 *
 * ── HARNESS (deliberate deviation from the generic facet header contract) ────
 * `waitForDropSettle` DOES NOT EXIST in this repo (repo-wide grep: no
 * definition), and the plain `query-manager-toggle-button` beforeEach leaves the
 * Table too short for its cells to be reachable. This spec reuses the
 * proven-green Table harness shared by basics.cy.js / inspector.cy.js /
 * contexts.cy.js / variants/string.cy.js: viewport → drag → hideTooltip →
 * modifyCanvasSize → close the settings panel → resizeTableWidget →
 * resizeQueryPanel('1') → openEditorSidebar. Exactly ONE cy.dragAndDropWidget
 * per test — cypress-real-dnd establishes its CDP intercept once per AUT load,
 * so a second drag in the same test silently never lands (F27 also notes that
 * cy.dragAndDropWidget clicks `right-sidebar-components-button` itself, so this
 * spec must NOT toggle that panel).
 *
 * ── TWO-NODE WIDGET ─────────────────────────────────────────────────────────
 * The Table renders `draggable-widget-table1` on BOTH the outer RenderWidget
 * wrapper AND its inner <table>, so `openStateFromComponent` / `openNode` /
 * `openAndVerifyNode` throw here (their internal realHover is unscoped). This
 * facet asserts only rendered-canvas + popover DOM, so it needs neither.
 *
 * ── POPOVER LIFECYCLE (load-bearing) ────────────────────────────────────────
 * The column popover is an OverlayTrigger with a CONTROLLED `show`
 * (Table.jsx:536-543) whose rootClose is disabled while any CodeHinter preview
 * popover is open (usePopoverState.js:33-43). A canvas click therefore may NOT
 * close it — every test closes it with `closeColumnPopover(<column>)`, which
 * re-clicks the list item and asserts the popover is gone. It also means
 * openColumnPopover() must never be called while the popover is already open
 * (the same click would toggle it shut).
 *
 * ── PRODUCT BUGS HONOURED HERE (not papered over) ────────────────────────────
 *  F1 (HIGH) no validation control has a usable data-cy — `getValidationList`
 *      writes `dateCy` (ValidationProperties.jsx:75,79,85,91) while every render
 *      branch reads `validation.dataCy` (:179,199,216), so React drops the
 *      attribute. setColumnValidation / verifyColumnValidation select on LABEL
 *      TEXT as the documented workaround.
 *  F18       a duplicated column KEEPS ITS NAME (listItemHelpers.js:45-48 swaps
 *      only the uuid), so two list items — and two rendered <th> — share a
 *      data-cy. Asserted explicitly below.
 *  F19       the column-list data-cy is NOT normalised (Table.jsx:571
 *      interpolates the raw display name), so all helpers use `columnListItem`
 *      rather than the older normalising `tableSelector.columnItem`.
 *  F21       cell colour must be read from `cellContentNode`
 *      (`div:not(:has(div))`), never `cellContent` (`<td> div`). For a READ-ONLY
 *      number cell that resolves to NumberRenderer.jsx:208-218, the single div
 *      that carries the inline `color`. (It is NOT usable once the column is
 *      editable — the editable branch, :141-196, mounts an <input> plus a
 *      two-div `.arror-container`.)
 *  F28 (MED) NEW — `maxValue` cannot see `cellValue`. `_helpers/utils.js:448`
 *      calls `resolveWidgetFieldValue(maxValue, currentState, undefined,
 *      customResolveObjects)` with FOUR arguments against the three-parameter
 *      signature `(prop, _default, customResolveObjects)` declared at :386, so
 *      `customResolveObjects` lands as `undefined` and any `{{cellValue…}}`
 *      max-value expression resolves to undefined — which makes the check
 *      SILENTLY SKIP (`resolvedMaxValue !== undefined` is false). minValue (:438)
 *      and customRule (:459) pass three arguments and behave correctly. The
 *      Max value it-block therefore uses a LITERAL, and says why.
 *  F29 (LOW) NEW — the Decimal Places field has NO data-cy. Every sibling field
 *      in PropertiesTabElements carries a wrapper data-cy (:118, :164, :182,
 *      :201, :220, :296, :312) but the Decimal Places wrapper at :368 has none,
 *      and its CodeHinter is mounted without a paramLabel so the editor itself is
 *      only the non-unique `-input-field`. `tableSelector.columnDecimalPlacesField`
 *      reaches it structurally as the one `.field.mb-2.px-3` without a data-cy.
 *
 * Helpers (all resolved through cypress/support/componentAutomation/type-helper-index.md):
 *   components/table.js — resizeTableWidget, setTableData, openColumnPopover,
 *     closeColumnPopover, switchColumnTab, setColumnType, addColumnOfType,
 *     duplicateColumn, deleteColumn, verifyAndEnterColumnOptionInput,
 *     setColumnCodeField, verifyColumnCodeField, setColumnProperty,
 *     verifyColumnProperty, toggleColumnProperty, toggleColumnFx,
 *     verifyColumnFxAbsent, setColumnColor, verifyColumnColor,
 *     setColumnValidation, verifyColumnValidation, setColumnAlignment,
 *     setPinPosition, verifyCellType, verifyCellValue, verifySingleValueOnTable,
 *     addInputOnTable, verifyInvalidFeedback
 *   appBuilder/properties.js — openEditorSidebar
 *   appBuilder/styles.js — verifyWidgetColorCss
 *   appBuilder/querymanager/queryPanel.js — resizeQueryPanel
 */
