const URL_ATTRIBUTES = ['href', 'src', 'cite', 'action', 'poster', 'background', 'xlink:href'];
const SAFE_SCHEMES = ['http', 'https', 'ftp', 'mailto', 'tel', 'callto', 'sms', 'cid', 'xmpp'];
const MEDIA_SCHEMES = [...SAFE_SCHEMES, 'data'];
const LINK_TAGS = ['a', 'area', 'form'];

// <use> must only reference fragments in the same document; external or data:
// targets can smuggle script-bearing SVG.
const keepFragmentHrefOnly = (tagName, attribs) => {
  const next = { ...attribs };
  ['href', 'xlink:href'].forEach((attr) => {
    if (next[attr] !== undefined && !String(next[attr]).trim().startsWith('#')) delete next[attr];
  });
  return { tagName, attribs: next };
};

const linkTargetTransform = (linksInNewTab) => (tagName, attribs) => {
  const next = { ...attribs };
  if (linksInNewTab) {
    next.target = '_blank';
    next.rel = 'noopener';
  } else {
    delete next.target;
  }
  return { tagName, attribs: next };
};

const buildOptions = ({ allowedTags, linksInNewTab = false, allowStyleTag = false }) => ({
  allowedTags: allowStyleTag ? [...allowedTags, 'style'] : allowedTags,
  allowVulnerableTags: allowStyleTag,
  allowedAttributes: {
    '*': [...HTML_ATTRIBUTES, ...SVG_ATTRIBUTES],
    a: ['target'],
    area: ['target'],
    form: ['target'],
  },
  allowedSchemes: SAFE_SCHEMES,
  allowedSchemesByTag: {
    img: MEDIA_SCHEMES,
    image: MEDIA_SCHEMES,
    source: MEDIA_SCHEMES,
    video: MEDIA_SCHEMES,
    audio: MEDIA_SCHEMES,
    track: MEDIA_SCHEMES,
  },
  allowedSchemesAppliedToAttributes: URL_ATTRIBUTES,
  allowProtocolRelative: true,
  // Inline style attributes pass through unparsed, as with DOMPurify. Parsing
  // them needs postcss's Node-only paths and drops the attribute on failure.
  parseStyleAttributes: false,
  disallowedTagsMode: 'discard',
  transformTags: {
    use: keepFragmentHrefOnly,
    ...Object.fromEntries(LINK_TAGS.map((tag) => [tag, linkTargetTransform(linksInNewTab)])),
  },
});

const HTML_OPTIONS = buildOptions({ allowedTags: [...HTML_TAGS, ...SVG_TAGS] });
const HTML_WIDGET_OPTIONS = buildOptions({
  allowedTags: [...HTML_TAGS, ...SVG_TAGS],
  linksInNewTab: true,
  allowStyleTag: true,
});
const SVG_OPTIONS = buildOptions({ allowedTags: SVG_TAGS });

const toMarkup = (dirty) => {
  if (dirty === null || dirty === undefined) return '';
  return typeof dirty === 'string' ? dirty : String(dirty);
};

/**
 * Sanitize untrusted HTML (with inline SVG) for rendering.
 *
 * @param {*} dirty - markup to clean; null/undefined become ''.
 * @param {object} [options]
 * @param {boolean} [options.htmlWidget] - Html widget mode: keeps <style> blocks the
 *   author wrote and forces links/forms to open in a new tab with rel="noopener".
 * @returns {string}
 */
export const sanitizeHtml = (dirty, { htmlWidget = false } = {}) =>
  sanitize(toMarkup(dirty), htmlWidget ? HTML_WIDGET_OPTIONS : HTML_OPTIONS);

/**
 * Sanitize untrusted SVG markup (SvgImage widget). Only SVG elements survive.
 *
 * @param {*} dirty - SVG markup; null/undefined become ''.
 * @returns {string}
 */
export const sanitizeSvg = (dirty) => sanitize(toMarkup(dirty), SVG_OPTIONS);
