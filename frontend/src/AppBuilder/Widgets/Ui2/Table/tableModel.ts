// ToolJet UI 2.0 Table: the table's data logic, kept apart from the component so it is tested on its own
// and stays cheap per row. Conventions follow the native Table (column keys, filter conditions, sortApplied); its known
// crash and correctness bugs are not repeated: search text is never a regex, numbers filter as numbers, export applies
// filters, sort and edits.
import type { CSSProperties } from 'react';
import dayjs from 'dayjs';
import { stringify } from '@/AppBuilder/Widgets/Ui2/_shared/packJson';
import type { Resolved } from '@/AppBuilder/Widgets/Ui2/_shared/types';
import type { ColumnLike, ColumnType, Row, TableColumn } from './types';
import { isEmptyValue, isSet } from '@/AppBuilder/Widgets/Ui2/_shared/values';
import { formatCell } from '@/AppBuilder/Widgets/Ui2/_shared/format';
import { cellText, patternKey, regexHolds, regexResults } from './tableRegex';
import type { UncheckedPatterns } from './tableRegex';

const falsy = (value: unknown): boolean => value === false || value === 'false' || value === '{{false}}';

const TYPE_ALIASES: Record<string, ColumnType> = {
  string: 'string',
  text: 'string',
  default: 'string',
  number: 'number',
  currency: 'currency',
  money: 'currency',
  date: 'date',
  datepicker: 'date',
  datetime: 'datetime',
  badge: 'badge',
  status: 'badge',
  select: 'badge',
  tags: 'tags',
  tagsV2: 'tags',
  newMultiSelect: 'tags',
  boolean: 'boolean',
  toggle: 'boolean',
  link: 'link',
  image: 'image',
  avatar: 'avatar',
  progress: 'progress',
  button: 'button',
  actions: 'button',
  json: 'json',
  html: 'html',
};
export const COLUMN_TYPES = [...new Set(Object.values(TYPE_ALIASES))];
const RIGHT_ALIGNED = new Set<string>(['number', 'currency']);
const NOT_DATA = new Set<string>(['button']);

/** A cell's value; `key` may be dotted (meta.team). */
export const readCell = (row: unknown, key: unknown): unknown => {
  if (!row || typeof row !== 'object' || !isSet(key)) return undefined;
  const fields = row as Row;
  if (String(key) in fields) return fields[String(key)];
  return String(key)
    .split('.')
    .reduce<unknown>((value, part) => (value && typeof value === 'object' ? (value as Row)[part] : undefined), row);
};

const inferType = (value: unknown): ColumnType =>
  typeof value === 'number' ? 'number' : typeof value === 'boolean' ? 'boolean' : 'string';

/** A table draws every column of every row on the page: past this many columns, a binding of rows bound as columns
 *  (10k of them) froze the page. */
export const MAX_COLUMNS = 100;

/** Columns as one shape, from native column objects ({key, name, columnType, ...}), the earlier pack keys ({dataIndex,
 *  title, kind, align}), or, when none are given, the keys of the first rows (nested objects skipped). */
export const normalizeColumns = (columns: unknown, data: unknown): TableColumn[] => {
  let source: Resolved[] = Array.isArray(columns)
    ? columns.filter((c) => c && typeof c === 'object' && !Array.isArray(c))
    : [];
  if (!source.length) {
    const sample: Row[] = (Array.isArray(data) ? data : [])
      .filter((row) => row && typeof row === 'object')
      .slice(0, 50);
    const seen = new Map<string, unknown>();
    sample.forEach((row) =>
      Object.keys(row).forEach((key) => {
        if (!seen.has(key)) seen.set(key, undefined);
        if (seen.get(key) === undefined && row[key] !== null && row[key] !== undefined) seen.set(key, row[key]);
      })
    );
    source = [...seen.entries()]
      .filter(([, value]) => !(value !== null && typeof value === 'object'))
      .map(([key, value]) => ({ key, name: key, columnType: inferType(value), autogenerated: true }));
  }
  const ids = new Set<string>();
  return source.slice(0, MAX_COLUMNS).map((c, index): TableColumn => {
    const key = String(c.key ?? c.dataIndex ?? c.accessor ?? c.name ?? c.title ?? `column${index + 1}`);
    const type = TYPE_ALIASES[c.columnType ?? c.kind ?? c.type] ?? 'string';
    let id = String(c.id ?? key);
    for (let n = 2; ids.has(id); n += 1) id = `${c.id ?? key}-${n}`;
    ids.add(id);
    return {
      id,
      key,
      name: String(c.name ?? c.title ?? c.header ?? key),
      type,
      align: c.horizontalAlignment ?? c.align ?? (RIGHT_ALIGNED.has(type) ? 'right' : 'left'),
      width: Number(c.columnSize ?? c.width) || undefined,
      minWidth: Number(c.minWidth) || undefined,
      visible: !falsy(c.columnVisibility ?? c.visible),
      sortable: !NOT_DATA.has(type) && !falsy(c.sortable),
      searchable: !NOT_DATA.has(type) && !falsy(c.searchable),
      editable:
        !NOT_DATA.has(type) && (c.isEditable === true || c.isEditable === 'true' || c.isEditable === '{{true}}'),
      pin: c.pinPosition === 'left' || c.pinPosition === 'right' ? c.pinPosition : undefined,
      wrap: c.wrap === true,
      format: {
        decimalPlaces: isSet(c.decimalPlaces) ? Math.max(0, Math.min(10, Number(c.decimalPlaces) || 0)) : undefined,
        currency: c.currency,
        locale: c.locale,
        dateFormat: c.dateFormat,
        prefix: c.prefix,
        suffix: c.suffix,
      },
      options: Array.isArray(c.options) ? c.options : undefined,
      badgeColors: c.badgeColors && typeof c.badgeColors === 'object' ? c.badgeColors : undefined,
      buttons: Array.isArray(c.buttons) ? c.buttons.filter((b: unknown) => b && typeof b === 'object') : undefined,
      textColor: c.textColor,
      cellBackgroundColor: c.cellBackgroundColor,
      fontWeight: c.fontWeight,
      linkText: c.displayText ?? c.linkText,
      openInNewTab: c.linkTarget !== '_self' && c.openInNewTab !== false,
      imageShape: c.imageShape,
      maxValue: Number(c.maxValue) || 100,
      transformation: typeof c.transformation === 'string' ? c.transformation : undefined,
      // Declarative per-row styling: [{ key?, condition, value, textColor, backgroundColor, fontWeight }], first match
      // wins. A binding nested inside the columns binding would end it at the first "}}", so rules are data.
      conditionalStyles: Array.isArray(c.conditionalStyles)
        ? c.conditionalStyles.filter(
            (r: Resolved) => r && typeof r === 'object' && FILTER_CONDITIONS.some(([k]) => k === r.condition)
          )
        : [],
    };
  });
};

/** Case-insensitive substring match over the searchable visible columns; the text is never a regex. */
export const matchesSearch = (row: unknown, columns: TableColumn[], text: unknown): boolean => {
  const needle = String(text ?? '')
    .trim()
    .toLowerCase();
  if (!needle) return true;
  return columns.some((column) => {
    if (!column.visible || !column.searchable) return false;
    const value = readCell(row, column.key);
    if (isEmptyValue(value)) return false;
    return (
      formatCell(value, column).toLowerCase().includes(needle) ||
      (typeof value !== 'object' && String(value).toLowerCase().includes(needle))
    );
  });
};

const asNumber = (value: unknown): number => {
  if (typeof value === 'number') return value;
  if (typeof value !== 'string' || !value.trim()) return NaN;
  return Number(value.replace(/,/g, ''));
};
const asTime = (value: unknown): number => {
  if (isEmptyValue(value) || typeof value === 'boolean') return NaN;
  const parsed = dayjs(value as dayjs.ConfigType);
  return parsed.isValid() ? parsed.valueOf() : NaN;
};

/** Compares two cell values for sorting and filtering: numbers as numbers, dates as dates, else natural text order.
 *  Empty values are not compared here (callers put them last). */
export const compareCells = (a: unknown, b: unknown, type?: string): number => {
  if (type === 'number' || type === 'currency' || (typeof a === 'number' && typeof b === 'number')) {
    const x = asNumber(a);
    const y = asNumber(b);
    if (Number.isFinite(x) && Number.isFinite(y)) return x - y;
  }
  if (type === 'date' || type === 'datetime') {
    const x = asTime(a);
    const y = asTime(b);
    if (Number.isFinite(x) && Number.isFinite(y)) return x - y;
  }
  if (type === 'boolean') return Number(a === true || a === 'true') - Number(b === true || b === 'true');
  return String(typeof a === 'object' ? stringify(a) : a).localeCompare(
    String(typeof b === 'object' ? stringify(b) : b),
    undefined,
    { numeric: true, sensitivity: 'base' }
  );
};

/** The rows sorted by one column, empty values last in both directions. Returns a new array. */
export const sortRows = <T>(
  rows: T[],
  column: Pick<TableColumn, 'key' | 'type'> | undefined,
  direction: unknown
): T[] => {
  if (!column || (direction !== 'asc' && direction !== 'desc')) return rows;
  const sign = direction === 'desc' ? -1 : 1;
  return rows
    .map((row, index) => ({ row, index, value: readCell(row, column.key) }))
    .sort((p, q) => {
      const pe = isEmptyValue(p.value);
      const qe = isEmptyValue(q.value);
      if (pe || qe) return pe === qe ? p.index - q.index : pe ? 1 : -1;
      return sign * compareCells(p.value, q.value, column.type) || p.index - q.index;
    })
    .map((entry) => entry.row);
};

export const FILTER_CONDITIONS: [string, string][] = [
  ['contains', 'contains'],
  ['doesNotContains', 'does not contain'],
  ['matches', 'matches (regex)'],
  ['nl', 'does not match (regex)'],
  ['equals', 'equals'],
  ['ne', 'not equals'],
  ['isEmpty', 'is empty'],
  ['isNotEmpty', 'is not empty'],
  ['gt', 'greater than'],
  ['lt', 'less than'],
  ['gte', 'greater than or equal'],
  ['lte', 'less than or equal'],
];
const NO_VALUE = new Set<unknown>(['isEmpty', 'isNotEmpty']);

const passes = (
  value: unknown,
  condition: unknown,
  wanted: unknown,
  column?: ColumnLike,
  unchecked?: UncheckedPatterns
): boolean => {
  const text = cellText(value);
  const target = String(wanted ?? '').toLowerCase();
  switch (condition) {
    case 'contains':
      return text.includes(target);
    case 'doesNotContains':
      return !text.includes(target);
    case 'matches':
      return regexHolds(wanted, text, false, unchecked);
    case 'nl':
      return regexHolds(wanted, text, true, unchecked);
    case 'equals':
      return text === target || (Number.isFinite(asNumber(value)) && asNumber(value) === asNumber(wanted));
    case 'ne':
      return !(text === target || (Number.isFinite(asNumber(value)) && asNumber(value) === asNumber(wanted)));
    case 'isEmpty':
      return isEmptyValue(value) || (Array.isArray(value) && value.length === 0);
    case 'isNotEmpty':
      return !isEmptyValue(value) && !(Array.isArray(value) && value.length === 0);
    case 'gt':
    case 'lt':
    case 'gte':
    case 'lte': {
      if (isEmptyValue(value)) return false;
      const cmp = compareCells(
        value,
        wanted,
        column?.type === 'string' && Number.isFinite(asNumber(value)) ? 'number' : column?.type
      );
      return condition === 'gt' ? cmp > 0 : condition === 'lt' ? cmp < 0 : condition === 'gte' ? cmp >= 0 : cmp <= 0;
    }
    default:
      return true;
  }
};

/** Whether a value meets one of the filter conditions (used by filters, conditional styles and button rules); a regex
 *  pattern in `unchecked` (screenRegexRules on the dataset) holds for no value. */
export const matchesCondition = (
  value: unknown,
  condition: unknown,
  wanted: unknown,
  column?: ColumnLike,
  unchecked?: UncheckedPatterns
): boolean => passes(value, condition, wanted, column, unchecked);

/** A cell's style from its column's conditional rules: the first rule whose condition holds (on the cell, or on the
 *  row's `key` field when the rule names one), `unchecked` from screenRegexRules on the cell's dataset. */
export const cellStyleFor = (column: TableColumn, row: unknown, unchecked?: UncheckedPatterns): CSSProperties => {
  const rule = (column.conditionalStyles ?? []).find((r) => {
    const field = isSet(r.key) ? String(r.key) : column.key;
    const target = ruleColumn(column, field);
    return passes(readCell(row, field), r.condition, r.value, target, unchecked);
  });
  if (!rule) return {};
  return {
    ...(isSet(rule.textColor) ? { color: String(rule.textColor) } : {}),
    ...(isSet(rule.backgroundColor) ? { background: String(rule.backgroundColor) } : {}),
    ...(isSet(rule.fontWeight) ? { fontWeight: rule.fontWeight } : {}),
  };
};
// A rule on another field compares it by its own value type; the cell's column type only applies to the cell.
const ruleColumn = (column: TableColumn, field: string): ColumnLike =>
  field === column.key ? column : { type: 'string' };

/** The rows passing every complete filter ({column: key or header name, condition, value}); others are ignored. */
export const applyFilters = <T>(rows: T[], filters: unknown, columns: TableColumn[]): T[] => {
  const active = (Array.isArray(filters) ? filters : [])
    .map((f: Resolved | null) => {
      if (!f || typeof f !== 'object') return null;
      const column = columns.find((c) => c.key === f.column || c.name === f.column || c.id === f.column);
      if (!column || !FILTER_CONDITIONS.some(([c]) => c === f.condition)) return null;
      if (!NO_VALUE.has(f.condition) && !isSet(f.value)) return null;
      return { column, condition: f.condition, value: f.value };
    })
    .filter((f): f is { column: TableColumn; condition: string; value: unknown } => f !== null);
  if (!active.length) return rows;
  // A regex filter is tested on every row first: a pattern that cannot be checked on one row keeps no row (tableRegex).
  const matched = new Map<unknown, boolean[]>();
  for (const f of active) {
    if (f.condition !== 'matches' && f.condition !== 'nl') continue;
    const results = regexResults(f.value, rows, (row) => readCell(row, f.column.key));
    if (results === null) return [];
    if (results) matched.set(f, results);
  }
  return rows.filter((row, i) =>
    active.every((f) => {
      const results = matched.get(f);
      return results
        ? results[i] !== (f.condition === 'nl')
        : passes(readCell(row, f.column.key), f.condition, f.value, f.column);
    })
  );
};

/** Tests every column's regex style and button rules on every row of one dataset before a cell renders, and returns
 *  the patterns that could not be checked on some row: given to cellStyleFor and matchesCondition, such a rule holds
 *  for no row of this dataset, whatever the row order (tableRegex). The next dataset is screened on its own. */
export const screenRegexRules = (columns: TableColumn[], rows: unknown[]): Set<string> => {
  const unchecked = new Set<string>();
  const tested = new Set<string>();
  const screen = (rule: Resolved | null | undefined, field: unknown) => {
    if (!rule || typeof rule !== 'object' || (rule.condition !== 'matches' && rule.condition !== 'nl')) return;
    const key = patternKey(rule.value);
    const once = JSON.stringify([field, key]);
    if (key === null || unchecked.has(key) || tested.has(once)) return;
    tested.add(once);
    if (regexResults(rule.value, rows, (row) => readCell(row, field)) === null) unchecked.add(key);
  };
  for (const column of columns) {
    for (const r of column.conditionalStyles ?? []) screen(r, isSet(r.key) ? String(r.key) : column.key);
    for (const b of column.buttons ?? []) for (const rule of [b.hiddenWhen, b.disabledWhen]) screen(rule, rule?.key);
  }
  return unchecked;
};

const PRIMITIVE = new Set(['string', 'number', 'boolean']);

/** Whether a cell matches any of `values` by ==, as the native Table's selectRow, selectRows and deselectRows match, in
 *  one pass over the rows: comparing every value with every row took minutes for 10k values on 10k rows. Text, numbers
 *  and booleans of one type match as they are, of different types as numbers ('01' == 1, 0 == false); null and
 *  undefined match only each other; anything else (an object, a bigint) is compared with == itself. */
export const looseMatcher = (values: unknown[]): ((cell: unknown) => boolean) => {
  const same = new Set<unknown>();
  const asNumber = new Map<string, Set<number>>([...PRIMITIVE].map((type) => [type, new Set<number>()]));
  const other: unknown[] = [];
  let nullish = false;
  values.forEach((value) => {
    if (value === null || value === undefined) nullish = true;
    else if (PRIMITIVE.has(typeof value)) {
      const n = Number(value);
      // NaN equals nothing, itself included.
      if (Number.isNaN(n) && typeof value === 'number') return;
      same.add(value);
      if (!Number.isNaN(n)) asNumber.get(typeof value)?.add(n);
    } else other.push(value);
  });
  return (cell) => {
    if (cell === null || cell === undefined) return nullish;
    const type = typeof cell;
    if (!PRIMITIVE.has(type)) return values.some((value) => cell == value); // eslint-disable-line eqeqeq
    if (same.has(cell)) return true;
    const n = Number(cell);
    if (!Number.isNaN(n) && [...asNumber].some(([t, numbers]) => t !== type && numbers.has(n))) return true;
    return other.some((value) => cell == value); // eslint-disable-line eqeqeq
  };
};

/** A stable key for a row: its id field when it has one, else its position in the data. The two never share a key
 *  (a row with no id was taken for the row whose id is "#0"): an id key starts with "id:", a position key with "#". */
export const rowKey = (row: unknown, idField: string, index: number): string =>
  row && typeof row === 'object' && isSet(readCell(row, idField))
    ? `id:${String(readCell(row, idField))}`
    : `#${index}`;

const csvCell = (value: unknown): string => {
  if (isEmptyValue(value)) return '';
  let text: string = typeof value === 'object' ? stringify(value) : String(value);
  // A cell that starts like a formula is run by spreadsheets: prefix it so it is read as text. A line feed and the
  // full-width forms of the signs (＝＋－＠) start one in some spreadsheets too.
  if (/^[=+\-@\t\r\n\uFF1D\uFF0B\uFF0D\uFF20]/.test(text) && !(typeof value === 'number')) text = `'${text}`;
  return /[",\n\r]/.test(text) || text.startsWith("'") ? `"${text.replace(/"/g, '""')}"` : text;
};

/** The rows as CSV: visible data columns, header names, raw values. */
export const toCsv = (rows: unknown[], columns: TableColumn[]): string => {
  const cols = columns.filter((c) => c.visible && !NOT_DATA.has(c.type));
  const lines = [cols.map((c) => csvCell(c.name)).join(',')];
  rows.forEach((row) => lines.push(cols.map((c) => csvCell(readCell(row, c.key))).join(',')));
  return lines.join('\n');
};
