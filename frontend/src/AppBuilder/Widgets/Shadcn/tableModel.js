// shadcn/ui pack Table (experiment): the table's data logic, kept apart from the component so it is tested on its own
// and stays cheap per row. Conventions follow the native Table (column keys, filter conditions, sortApplied); its known
// crash and correctness bugs are not repeated: search text is never a regex, numbers filter as numbers, export applies
// filters, sort and edits.
import dayjs from 'dayjs';
import { stringify } from '../packJson';

const isSet = (value) => value !== undefined && value !== null && String(value).trim() !== '';
const isEmptyValue = (value) =>
  value === undefined || value === null || (typeof value === 'string' && value.trim() === '') || Number.isNaN(value);
const falsy = (value) => value === false || value === 'false' || value === '{{false}}';

const TYPE_ALIASES = {
  string: 'string',
  text: 'string',
  default: 'string',
  number: 'number',
  currency: 'currency',
  money: 'currency',
  date: 'date',
  datepicker: 'date',
  datetime: 'datetime',
  badge: 'badge',
  status: 'badge',
  select: 'badge',
  tags: 'tags',
  tagsV2: 'tags',
  newMultiSelect: 'tags',
  boolean: 'boolean',
  toggle: 'boolean',
  link: 'link',
  image: 'image',
  avatar: 'avatar',
  progress: 'progress',
  button: 'button',
  actions: 'button',
  json: 'json',
  html: 'html',
};
export const COLUMN_TYPES = [...new Set(Object.values(TYPE_ALIASES))];
const RIGHT_ALIGNED = new Set(['number', 'currency']);
const NOT_DATA = new Set(['button']);

/** A cell's value; `key` may be dotted (meta.team). */
export const readCell = (row, key) => {
  if (!row || typeof row !== 'object' || !isSet(key)) return undefined;
  if (key in row) return row[key];
  return String(key)
    .split('.')
    .reduce((value, part) => (value && typeof value === 'object' ? value[part] : undefined), row);
};

const inferType = (value) => (typeof value === 'number' ? 'number' : typeof value === 'boolean' ? 'boolean' : 'string');

/** A table draws every column of every row on the page: past this many columns, a binding of rows bound as columns
 *  (10k of them) froze the page. */
export const MAX_COLUMNS = 100;

/** Columns as one shape, from native column objects ({key, name, columnType, ...}), the earlier pack keys ({dataIndex,
 *  title, kind, align}), or, when none are given, the keys of the first rows (nested objects skipped). */
export const normalizeColumns = (columns, data) => {
  let source = Array.isArray(columns) ? columns.filter((c) => c && typeof c === 'object' && !Array.isArray(c)) : [];
  if (!source.length) {
    const sample = (Array.isArray(data) ? data : []).filter((row) => row && typeof row === 'object').slice(0, 50);
    const seen = new Map();
    sample.forEach((row) =>
      Object.keys(row).forEach((key) => {
        if (!seen.has(key)) seen.set(key, undefined);
        if (seen.get(key) === undefined && row[key] !== null && row[key] !== undefined) seen.set(key, row[key]);
      })
    );
    source = [...seen.entries()]
      .filter(([, value]) => !(value !== null && typeof value === 'object'))
      .map(([key, value]) => ({ key, name: key, columnType: inferType(value), autogenerated: true }));
  }
  const ids = new Set();
  return source.slice(0, MAX_COLUMNS).map((c, index) => {
    const key = String(c.key ?? c.dataIndex ?? c.accessor ?? c.name ?? c.title ?? `column${index + 1}`);
    const type = TYPE_ALIASES[c.columnType ?? c.kind ?? c.type] ?? 'string';
    let id = String(c.id ?? key);
    for (let n = 2; ids.has(id); n += 1) id = `${c.id ?? key}-${n}`;
    ids.add(id);
    return {
      id,
      key,
      name: String(c.name ?? c.title ?? c.header ?? key),
      type,
      align: c.horizontalAlignment ?? c.align ?? (RIGHT_ALIGNED.has(type) ? 'right' : 'left'),
      width: Number(c.columnSize ?? c.width) || undefined,
      minWidth: Number(c.minWidth) || undefined,
      visible: !falsy(c.columnVisibility ?? c.visible),
      sortable: !NOT_DATA.has(type) && !falsy(c.sortable),
      searchable: !NOT_DATA.has(type) && !falsy(c.searchable),
      editable:
        !NOT_DATA.has(type) && (c.isEditable === true || c.isEditable === 'true' || c.isEditable === '{{true}}'),
      pin: c.pinPosition === 'left' || c.pinPosition === 'right' ? c.pinPosition : undefined,
      wrap: c.wrap === true,
      format: {
        decimalPlaces: isSet(c.decimalPlaces) ? Math.max(0, Math.min(10, Number(c.decimalPlaces) || 0)) : undefined,
        currency: c.currency,
        locale: c.locale,
        dateFormat: c.dateFormat,
        prefix: c.prefix,
        suffix: c.suffix,
      },
      options: Array.isArray(c.options) ? c.options : undefined,
      badgeColors: c.badgeColors && typeof c.badgeColors === 'object' ? c.badgeColors : undefined,
      buttons: Array.isArray(c.buttons) ? c.buttons.filter((b) => b && typeof b === 'object') : undefined,
      textColor: c.textColor,
      cellBackgroundColor: c.cellBackgroundColor,
      fontWeight: c.fontWeight,
      linkText: c.displayText ?? c.linkText,
      openInNewTab: c.linkTarget !== '_self' && c.openInNewTab !== false,
      imageShape: c.imageShape,
      maxValue: Number(c.maxValue) || 100,
      transformation: typeof c.transformation === 'string' ? c.transformation : undefined,
      // Declarative per-row styling: [{ key?, condition, value, textColor, backgroundColor, fontWeight }], first match
      // wins. A binding nested inside the columns binding would end it at the first "}}", so rules are data.
      conditionalStyles: Array.isArray(c.conditionalStyles)
        ? c.conditionalStyles.filter(
            (r) => r && typeof r === 'object' && FILTER_CONDITIONS.some(([k]) => k === r.condition)
          )
        : [],
    };
  });
};

// Intl.NumberFormat is costly to build; a table formats every cell on each search, so formatters are reused.
const FORMATTERS = new Map();
const numberFormatter = (locale, options) => {
  const key = `${locale}|${stringify(options)}`;
  if (!FORMATTERS.has(key)) {
    if (FORMATTERS.size > 200) FORMATTERS.clear();
    FORMATTERS.set(key, new Intl.NumberFormat(locale, options));
  }
  return FORMATTERS.get(key);
};

const DEFAULT_DATE = 'DD MMM YYYY';
const DEFAULT_DATETIME = 'DD MMM YYYY, HH:mm';

/** A cell as text: what the table shows for plain types, searches and exports. Never throws. */
export const formatCell = (value, column = {}) => {
  try {
    if (isEmptyValue(value)) return '';
    const { type = 'string', format = {} } = column;
    const wrap = (text) => `${format.prefix ?? ''}${text}${format.suffix ?? ''}`;
    if (type === 'number' || type === 'currency') {
      const n = typeof value === 'number' ? value : Number(String(value).replace(/,/g, ''));
      if (!Number.isFinite(n)) return String(value);
      const digits = format.decimalPlaces;
      const options =
        type === 'currency'
          ? {
              style: 'currency',
              currency: String(format.currency || 'USD').toUpperCase(),
              minimumFractionDigits: digits ?? 2,
              maximumFractionDigits: digits ?? 2,
            }
          : { minimumFractionDigits: digits ?? 0, maximumFractionDigits: digits ?? 2 };
      return wrap(numberFormatter(format.locale || 'en-US', options).format(n));
    }
    if (type === 'date' || type === 'datetime') {
      const parsed = typeof value === 'number' ? dayjs(value < 1e12 ? value * 1000 : value) : dayjs(value);
      if (!parsed.isValid()) return String(value);
      return wrap(parsed.format(format.dateFormat || (type === 'datetime' ? DEFAULT_DATETIME : DEFAULT_DATE)));
    }
    if (type === 'boolean') return value === true || value === 'true' ? 'Yes' : 'No';
    if (type === 'tags')
      return (Array.isArray(value) ? value : String(value).split(',')).map((t) => String(t).trim()).join(', ');
    if (typeof value === 'object') return stringify(value);
    return wrap(String(value));
  } catch {
    return '';
  }
};

/** Case-insensitive substring match over the searchable visible columns; the text is never a regex. */
export const matchesSearch = (row, columns, text) => {
  const needle = String(text ?? '')
    .trim()
    .toLowerCase();
  if (!needle) return true;
  return columns.some((column) => {
    if (!column.visible || !column.searchable) return false;
    const value = readCell(row, column.key);
    if (isEmptyValue(value)) return false;
    return (
      formatCell(value, column).toLowerCase().includes(needle) ||
      (typeof value !== 'object' && String(value).toLowerCase().includes(needle))
    );
  });
};

const asNumber = (value) => {
  if (typeof value === 'number') return value;
  if (typeof value !== 'string' || !value.trim()) return NaN;
  return Number(value.replace(/,/g, ''));
};
const asTime = (value) => {
  if (isEmptyValue(value) || typeof value === 'boolean') return NaN;
  const parsed = dayjs(value);
  return parsed.isValid() ? parsed.valueOf() : NaN;
};

/** Compares two cell values for sorting and filtering: numbers as numbers, dates as dates, else natural text order.
 *  Empty values are not compared here (callers put them last). */
export const compareCells = (a, b, type) => {
  if (type === 'number' || type === 'currency' || (typeof a === 'number' && typeof b === 'number')) {
    const x = asNumber(a);
    const y = asNumber(b);
    if (Number.isFinite(x) && Number.isFinite(y)) return x - y;
  }
  if (type === 'date' || type === 'datetime') {
    const x = asTime(a);
    const y = asTime(b);
    if (Number.isFinite(x) && Number.isFinite(y)) return x - y;
  }
  if (type === 'boolean') return Number(a === true || a === 'true') - Number(b === true || b === 'true');
  return String(typeof a === 'object' ? stringify(a) : a).localeCompare(
    String(typeof b === 'object' ? stringify(b) : b),
    undefined,
    { numeric: true, sensitivity: 'base' }
  );
};

/** The rows sorted by one column, empty values last in both directions. Returns a new array. */
export const sortRows = (rows, column, direction) => {
  if (!column || (direction !== 'asc' && direction !== 'desc')) return rows;
  const sign = direction === 'desc' ? -1 : 1;
  return rows
    .map((row, index) => ({ row, index, value: readCell(row, column.key) }))
    .sort((p, q) => {
      const pe = isEmptyValue(p.value);
      const qe = isEmptyValue(q.value);
      if (pe || qe) return pe === qe ? p.index - q.index : pe ? 1 : -1;
      return sign * compareCells(p.value, q.value, column.type) || p.index - q.index;
    })
    .map((entry) => entry.row);
};

export const FILTER_CONDITIONS = [
  ['contains', 'contains'],
  ['doesNotContains', 'does not contain'],
  ['matches', 'matches (regex)'],
  ['nl', 'does not match (regex)'],
  ['equals', 'equals'],
  ['ne', 'not equals'],
  ['isEmpty', 'is empty'],
  ['isNotEmpty', 'is not empty'],
  ['gt', 'greater than'],
  ['lt', 'less than'],
  ['gte', 'greater than or equal'],
  ['lte', 'less than or equal'],
];
const NO_VALUE = new Set(['isEmpty', 'isNotEmpty']);

const safeRegex = (pattern) => {
  try {
    return new RegExp(pattern, 'i');
  } catch {
    return null;
  }
};

const passes = (value, condition, wanted, column) => {
  const text = (isEmptyValue(value) ? '' : typeof value === 'object' ? stringify(value) : String(value)).toLowerCase();
  const target = String(wanted ?? '').toLowerCase();
  switch (condition) {
    case 'contains':
      return text.includes(target);
    case 'doesNotContains':
      return !text.includes(target);
    case 'matches': {
      const re = safeRegex(wanted);
      return re ? re.test(text) : false;
    }
    case 'nl': {
      const re = safeRegex(wanted);
      return re ? !re.test(text) : true;
    }
    case 'equals':
      return text === target || (Number.isFinite(asNumber(value)) && asNumber(value) === asNumber(wanted));
    case 'ne':
      return !(text === target || (Number.isFinite(asNumber(value)) && asNumber(value) === asNumber(wanted)));
    case 'isEmpty':
      return isEmptyValue(value) || (Array.isArray(value) && value.length === 0);
    case 'isNotEmpty':
      return !isEmptyValue(value) && !(Array.isArray(value) && value.length === 0);
    case 'gt':
    case 'lt':
    case 'gte':
    case 'lte': {
      if (isEmptyValue(value)) return false;
      const cmp = compareCells(
        value,
        wanted,
        column?.type === 'string' && Number.isFinite(asNumber(value)) ? 'number' : column?.type
      );
      return condition === 'gt' ? cmp > 0 : condition === 'lt' ? cmp < 0 : condition === 'gte' ? cmp >= 0 : cmp <= 0;
    }
    default:
      return true;
  }
};

/** Whether a value meets one of the filter conditions (used by filters, conditional styles and button rules). */
export const matchesCondition = (value, condition, wanted, column) => passes(value, condition, wanted, column);

/** A cell's style from its column's conditional rules: the first rule whose condition holds (on the cell, or on the
 *  row's `key` field when the rule names one). */
export const cellStyleFor = (column, row) => {
  const rule = (column.conditionalStyles ?? []).find((r) => {
    const field = isSet(r.key) ? String(r.key) : column.key;
    const target = ruleColumn(column, field);
    return passes(readCell(row, field), r.condition, r.value, target);
  });
  if (!rule) return {};
  return {
    ...(isSet(rule.textColor) ? { color: String(rule.textColor) } : {}),
    ...(isSet(rule.backgroundColor) ? { background: String(rule.backgroundColor) } : {}),
    ...(isSet(rule.fontWeight) ? { fontWeight: rule.fontWeight } : {}),
  };
};
// A rule on another field compares it by its own value type; the cell's column type only applies to the cell.
const ruleColumn = (column, field) => (field === column.key ? column : { type: 'string' });

/** The rows passing every complete filter ({column: key or header name, condition, value}); others are ignored. */
export const applyFilters = (rows, filters, columns) => {
  const active = (Array.isArray(filters) ? filters : [])
    .map((f) => {
      if (!f || typeof f !== 'object') return null;
      const column = columns.find((c) => c.key === f.column || c.name === f.column || c.id === f.column);
      if (!column || !FILTER_CONDITIONS.some(([c]) => c === f.condition)) return null;
      if (!NO_VALUE.has(f.condition) && !isSet(f.value)) return null;
      return { column, condition: f.condition, value: f.value };
    })
    .filter(Boolean);
  if (!active.length) return rows;
  return rows.filter((row) => active.every((f) => passes(readCell(row, f.column.key), f.condition, f.value, f.column)));
};

/** A stable key for a row: its id field when it has one, else its position in the data. */
export const rowKey = (row, idField, index) =>
  row && typeof row === 'object' && isSet(readCell(row, idField)) ? String(readCell(row, idField)) : `#${index}`;

const csvCell = (value) => {
  if (isEmptyValue(value)) return '';
  let text = typeof value === 'object' ? stringify(value) : String(value);
  // A cell that starts like a formula is run by spreadsheets: prefix it so it is read as text.
  if (/^[=+\-@\t\r]/.test(text) && !(typeof value === 'number')) text = `'${text}`;
  return /[",\n\r]/.test(text) || text.startsWith("'") ? `"${text.replace(/"/g, '""')}"` : text;
};

/** The rows as CSV: visible data columns, header names, raw values. */
export const toCsv = (rows, columns) => {
  const cols = columns.filter((c) => c.visible && !NOT_DATA.has(c.type));
  const lines = [cols.map((c) => csvCell(c.name)).join(',')];
  rows.forEach((row) => lines.push(cols.map((c) => csvCell(readCell(row, c.key))).join(',')));
  return lines.join('\n');
};
