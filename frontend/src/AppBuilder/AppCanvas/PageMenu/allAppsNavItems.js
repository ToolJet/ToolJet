// Expands each "All apps" nav item into links to the released apps the viewer can open.
// Pure: the caller supplies the app list and the expression scope.
import {
  extractAndReplaceReferencesFromString,
  getDynamicVariables,
  removeNestedDoubleCurlyBraces,
  resolveCode,
  resolveDynamicValues,
} from '@/AppBuilder/_stores/utils';

export const ALL_APPS_TYPE = 'all_apps';
// Same app-window glyph as "Add nav item ToolJet app": each generated entry is a link to one app.
// Fixed for now; per-app icons would need the app's icon on the menu-apps response.
export const GENERATED_APP_ICON = 'IconAppWindow';
const FOLDER_ICON = 'IconFolder';

const byName = (a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: 'base' });

/** What a hide expression can read as `app`. */
export const toAppContext = (menuApp) => ({
  id: menuApp.id,
  name: menuApp.name,
  folder_id: menuApp.folder?.id ?? null,
  folder_name: menuApp.folder?.name ?? null,
});

// Generated entries get `handle = id`: the menu renderers key list items by handle.
const appLink = (item, menuApp, parentId) => ({
  id: `${item.id}:app:${menuApp.id}`,
  handle: `${item.id}:app:${menuApp.id}`,
  name: menuApp.name,
  icon: GENERATED_APP_ICON,
  type: 'app',
  openIn: item.openIn,
  targetSlug: menuApp.slug,
  isGeneratedAppLink: true,
  isPageGroup: false,
  pageGroupId: parentId,
  disabled: false,
});

const folderGroup = (item, folder) => ({
  id: `${item.id}:folder:${folder.id}`,
  handle: `${item.id}:folder:${folder.id}`,
  name: folder.name,
  icon: FOLDER_ICON,
  type: 'group',
  isGeneratedAppLink: true,
  isPageGroup: true,
  pageGroupId: null,
  disabled: false,
});

/**
 * Links for one "All apps" item, in menu order. Grouped: one group per folder (folders by
 * name), each holding its apps, then apps without a folder. Flat: apps by name. Hidden apps
 * are dropped first, so a folder whose apps are all hidden never appears. An item that
 * already sits inside a nav group is listed flat, since groups do not nest.
 */
export const linksForAllAppsItem = (item, visibleApps) => {
  const parentId = item.pageGroupId ?? null;
  const apps = [...visibleApps].sort(byName);

  if (!item.groupByFolder || parentId) {
    return apps.map((menuApp) => appLink(item, menuApp, parentId));
  }

  const folders = new Map();
  const withoutFolder = [];
  for (const menuApp of apps) {
    if (!menuApp.folder) {
      withoutFolder.push(menuApp);
      continue;
    }
    const entry = folders.get(menuApp.folder.id) ?? { folder: menuApp.folder, apps: [] };
    entry.apps.push(menuApp);
    folders.set(menuApp.folder.id, entry);
  }

  const grouped = [...folders.values()]
    .sort((a, b) => byName(a.folder, b.folder))
    .flatMap(({ folder, apps: folderApps }) => {
      const group = folderGroup(item, folder);
      return [group, ...folderApps.map((menuApp) => appLink(item, menuApp, group.id))];
    });

  return [...grouped, ...withoutFolder.map((menuApp) => appLink(item, menuApp, null))];
};

/**
 * Replaces every "All apps" item in `pages` with its generated links, in place. The current
 * app is never listed. `isHidden(item, appContext)` decides each app.
 */
export const expandAllAppsNavItems = (pages, menuApps, { currentAppId, isHidden }) => {
  if (!pages.some((page) => page?.type === ALL_APPS_TYPE)) return pages;

  const candidates = (menuApps ?? []).filter((menuApp) => menuApp.id !== currentAppId);

  return pages.flatMap((page) => {
    if (page?.type !== ALL_APPS_TYPE) return [page];
    if (page.disabled) return [];
    const visibleApps = candidates.filter((menuApp) => !isHidden(page, toAppContext(menuApp)));
    return linksForAllAppsItem(page, visibleApps);
  });
};

/**
 * The menu tree. With nav groups enabled every group nests its children (`buildTree`).
 * Without them, manual groups stay flat as before, but folder groups generated by an
 * "All apps" item still nest their apps: grouping by folder is not a licensed feature.
 */
export const buildMenuTree = (pages, { navGroupsEnabled, buildTree }) => {
  if (navGroupsEnabled) return buildTree(pages);

  const folderGroups = new Map(
    pages
      .filter((page) => page?.isGeneratedAppLink && page.isPageGroup)
      .map((group) => [group.id, { ...group, children: [] }])
  );
  if (!folderGroups.size) return pages;

  const tree = [];
  for (const page of pages) {
    const group = folderGroups.get(page?.id);
    if (group) {
      tree.push(group);
      continue;
    }
    const parent = page?.isGeneratedAppLink ? folderGroups.get(page.pageGroupId) : undefined;
    if (parent) parent.children.push(page);
    else tree.push(page);
  }
  return tree;
};

/**
 * Evaluates an "All apps" item's `hidden` setting for one app. Returns `{ hidden, error }`.
 * A broken expression hides the app: the menu should never show what it cannot vouch for.
 */
export const evaluateAllAppsHidden = (hiddenSetting, appContext, { exposedValues, componentIds, queryIds }) => {
  const raw = hiddenSetting?.value ?? hiddenSetting;
  if (typeof raw !== 'string') return { hidden: !!raw, error: null };
  if (!raw.includes('{{')) return { hidden: raw.trim() === 'true', error: null };

  const { valueWithBrackets } = extractAndReplaceReferencesFromString(raw, componentIds, queryIds);
  const expression = valueWithBrackets.trim();
  const isSingleExpression =
    expression.startsWith('{{') && expression.endsWith('}}') && getDynamicVariables(expression)?.length === 1;

  if (isSingleExpression) {
    const [result, error] = resolveCode(
      removeNestedDoubleCurlyBraces(expression),
      exposedValues,
      { app: appContext },
      true
    );
    return error ? { hidden: true, error } : { hidden: !!result, error: null };
  }

  const result = resolveDynamicValues(expression, exposedValues, { app: appContext });
  return { hidden: result === true || result === 'true', error: null };
};
