/** The Ant icon a name means: an @ant-design/icons name (SearchOutlined), or a plain word (search, shopping-cart). */
export const antIcon = (name: unknown): React.ComponentType | null => {
  const raw = typeof name === 'string' ? name.trim() : '';
  if (!raw) return null;
  if (ANT[raw]) return ANT[raw];
  const key = raw.toLowerCase().replace(/^icon/, '').replace(/(outlined|filled|twotone|icon)$/, '').replace(/[^a-z0-9]/g, '');
  const mapped = WORDS[key] ?? NAMES.find((k) => k.toLowerCase() === `${key}outlined`);
  return mapped ? ANT[mapped] ?? null : null;
};

export const iconOr = (value: string): React.ReactNode => {
  const Icon = antIcon(value);
  if (Icon) return <Icon />;
  return value || undefined;
};
