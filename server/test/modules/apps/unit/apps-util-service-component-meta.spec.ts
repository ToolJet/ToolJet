import { AppsUtilService } from '@modules/apps/util.service';

/**
 * buildComponentMetaDefinition layers a component's saved properties over its widget defaults.
 * The KeyValuePair widget's default `fields` list ends with a `Status` field; a saved list shorter than
 * the default must stay exactly as saved, otherwise the default entries at the missing positions leak
 * back in (a "Status" row nobody added, or a deleted field coming back after a copy/paste).
 */
describe('AppsUtilService.buildComponentMetaDefinition — saved KeyValuePair fields', () => {
  const service = Object.create(AppsUtilService.prototype) as AppsUtilService;

  const field = (key: string) => ({ id: `id-${key}`, name: key, key, fieldType: 'string', autogenerated: true });

  const keyValuePair = (properties: Record<string, unknown>) => ({
    kvp: {
      component: { name: 'keyvaluepair1', component: 'KeyValuePair', definition: { properties } },
      layouts: {},
    },
  });

  const mergedFieldKeys = (properties: Record<string, unknown>) => {
    const merged = service.buildComponentMetaDefinition(keyValuePair(properties));
    return merged.kvp.component.definition.properties.fields.value.map((f: { key: string }) => f.key);
  };

  it('keeps a saved field list shorter than the default list as saved', () => {
    const saved = ['name', 'email', 'id', 'joined_date', 'department', 'salary', 'is_active'];

    expect(mergedFieldKeys({ fields: { value: saved.map(field) } })).toEqual(saved);
  });

  it('does not bring back a default field after the saved list is shortened', () => {
    expect(mergedFieldKeys({ fields: { value: [field('name')] } })).toEqual(['name']);
  });

  it('keeps an empty saved field list empty', () => {
    expect(mergedFieldKeys({ fields: { value: [] } })).toEqual([]);
  });

  it('keeps a saved field list longer than the default list as saved', () => {
    const saved = Array.from({ length: 12 }, (_, i) => `key_${i}`);

    expect(mergedFieldKeys({ fields: { value: saved.map(field) } })).toEqual(saved);
  });

  it('still gives the default fields to a component that has not saved any', () => {
    const keys = mergedFieldKeys({});

    expect(keys[0]).toBe('name');
    expect(keys).toContain('status');
  });
});
